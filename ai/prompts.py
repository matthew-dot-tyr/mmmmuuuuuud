TURN_SYSTEM = f"""Ты ведёшь уже начатый учебный диалог переговоров в роли оппонента и игрового судьи. Пишешь на русском языке.
{COMMON_RULES}
- Если ends=false: counterpart_reply — следующая реплика оппонента, естественно продолжающая диалог с учётом хода игрока.
- Если ends=true: counterpart_reply — заключительная реплика оппонента (соглашение, отказ или разрыв переговоров), и дополнительно:
  outcome "success" — если по итогу ВСЕГО диалога игрок добился выгодной или приемлемой договорённости, не поддавшись давлению и не сделав бессмысленных уступок; иначе "failure".
  score (только при success) от 1 до 10: 1-3 едва справился, 4-6 нормально, 7-8 хорошо, 9-10 образцово — оценивай весь диалог, а не только последний ход.
  feedback — структурный разбор диалога, объект с полями (обращайся на «вы», без id методик — называй их словами):
    "broke_quote": точная цитата ОДНОЙ конкретной реплики ИГРОКА (скопируй её из "ДИАЛОГ ДО ЭТОГО ХОДА" или
      из <реплика_игрока> этого хода дословно), в которой переговоры пошли не так; null, если ничего не
      сломалось (например, при чистом успехе).
    "broke_reason": почему именно эта реплика была проблемой; null вместе с broke_quote.
    "what_worked": что игрок сделал правильно за весь диалог; null, если буквально ничего не сработало.
    "alternative_phrasing": как стоило сформулировать вместо broke_quote; null, если broke_quote null.
    "tip": один конкретный совет на следующий раз — единственное обязательное поле, всегда заполнено."""


def _format_transcript(transcript: list) -> str:
    lines = []
    for t in transcript:
        speaker = "Оппонент" if t.speaker == "counterpart" else "Игрок"
        lines.append(f"{speaker}: {t.text}")
    return "\n".join(lines)


def turn_user(session, player_message: str, materials: str, force_end: bool = False) -> str:
    """
    force_end используется ТОЛЬКО скрытым техническим потолком SAFETY_MAX_TURNS
    (см. ai/contracts.py) — это не игровой лимит ходов, а редкий аварийный случай.
    В обычной игре force_end всегда False, и в промпте вообще нет упоминания числа ходов.
    """
    options_line = ""
    if not force_end and session.difficulty in OPTIONS_COUNT:
        options_line = f',\n  "options": [{{"text": "..."}}, ...]  // {OPTIONS_RULE.format(n=OPTIONS_COUNT[session.difficulty])}'

    final_note = (
        "\nЭти переговоры уже необычно сильно затянулись. Подведи итог ПРЯМО СЕЙЧАС: "
        '"ends" обязательно должно быть true.'
        if force_end else ""
    )

    return f"""МАТЕРИАЛЫ:
{materials}

СИТУАЦИЯ: {session.scenario_text}
ОППОНЕНТ: {session.counterpart_role}. Поведение: {session.counterpart_tone}
ЦЕЛЬ ОППОНЕНТА: {session.counterpart_goal}

ДИАЛОГ ДО ЭТОГО ХОДА:
{_format_transcript(session.transcript)}

<реплика_игрока>
{player_message}
</реплика_игрока>
{final_note}

Формат ответа при ends=false:
{{"ends": false, "counterpart_reply": "..."{options_line}}}

Формат ответа при ends=true:
{{"ends": true, "counterpart_reply": "...", "outcome": "success или failure", "score": число или null,
  "feedback": {{"broke_quote": "..." или null, "broke_reason": "..." или null,
                "what_worked": "..." или null, "alternative_phrasing": "..." или null,
                "tip": "..."}}}}"""
